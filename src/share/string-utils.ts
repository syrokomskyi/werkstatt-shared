/** Lowercase, dash-only kebab-case. Strips leading/trailing hyphens. */
export function toKebabCase(value: string): string {
  return value
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}
